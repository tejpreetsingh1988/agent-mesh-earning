"""Tests for mesh/worker_env.py and the Writer proof wiring.

Locally the `workers` module does not exist, so worker_env_value
must return None and callers must keep their os.environ path.
The Writer proof worker.py (regenerated by
scripts/sync-worker-proof.py) must pass the key explicitly from
worker_env_value — that wiring is what makes a dashboard secret
visible in the cloud, where os.environ never sees it.
"""
import pathlib

import pytest

from mesh.worker_env import effective_api_key, worker_env_value

_ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
_WRITER_WORKER = _ROOT / "cloudflare-proof" / "writer" / "src" / "worker.py"


def test_worker_env_value_none_locally():
    assert worker_env_value("OPENROUTER_API_KEY") is None


def test_effective_api_key_falls_back_to_environ(monkeypatch):
    monkeypatch.setenv("OPENROUTER_API_KEY", "env-key")
    assert effective_api_key() == "env-key"
    monkeypatch.delenv("OPENROUTER_API_KEY")
    assert effective_api_key() is None


def test_writer_proof_passes_worker_env_key():
    text = _WRITER_WORKER.read_text()
    assert 'worker_env_value("OPENROUTER_API_KEY")' in text
    assert "from mesh.worker_env import ai_binding, worker_env_value" in text
    assert "ai=ai_binding()" in text
